export type Lang = "ru" | "en";
const KEY = "app-lang";

let current: Lang = "ru";
if (typeof window !== "undefined") {
  try {
    if (window.localStorage.getItem(KEY) === "en") current = "en";
  } catch {
    /* ignore */
  }
}

export const getLang = () => current;
export const locale = () => (current === "en" ? "en-GB" : "ru-RU");

/** Switches the language and reloads so every label (incl. module-level ones) is re-evaluated. */
export function setLang(l: Lang) {
  window.localStorage.setItem(KEY, l);
  window.location.reload();
}

/** Translate a Russian source string; falls back to the original. */
export function t(ru: string): string {
  if (current === "ru") return ru;
  return EN[ru] ?? ru;
}

